package com.almarel.orion.brush.fawe.receipt;

/**
 * Итог сравнения "что реально лежит в слоте FAWE" и "что туда клал Орион".
 */
public enum SlotVerdict {

    /** Слот пуст, это дефолтная палочка или DTO помечен как ожидающий установки. Запись разрешена. */
    WRITABLE,

    /** В слоте тот самый объект, который установил Орион. Штатная обработка. */
    OWNED,

    /** Квитанция есть, но в слоте другой объект: инструмент поставил кто-то снаружи. DTO устарел. */
    FOREIGN,

    /** Квитанции нет, а в слоте недефолтный инструмент. Не трогать слот и не удалять DTO. */
    UNKNOWN
}