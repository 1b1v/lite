package com.almarel.orion.framework.storage;

/**
 * Результат попытки загрузки снапшота игрока из хранилища.
 *
 * [AI CONTEXT] НЕ схлопывать в boolean. SUCCESS и NO_DATA — оба "успешных"
 * с точки зрения дальнейшей работы (сессию можно сохранять), но означают
 * разное для логирования. FAILED — единственный исход, при котором
 * OrionSessionManager.markDataLoaded() вызывать ЗАПРЕЩЕНО: иначе периодическое
 * автосохранение затрет существующие данные игрока пустым снапшотом.
 */
public enum LoadOutcome {
    /** Данные успешно загружены и применены к сессии. */
    SUCCESS,
    /** У игрока действительно нет сохраненных данных (новый игрок). Безопасно. */
    NO_DATA,
    /** Ошибка при чтении БД или применении снапшота. Данные могли существовать. */
    FAILED
}