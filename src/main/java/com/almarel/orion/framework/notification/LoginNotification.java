package com.almarel.orion.framework.notification;

import net.kyori.adventure.text.Component;
import org.bukkit.entity.Player;

/**
 * Контракт для одного блока в агрегированном login-уведомлении.
 * Реализация отвечает ТОЛЬКО за контент и решение "показывать ли себя".
 * Оформление (рамка, разделители, порядок) — забота NotificationDigestService.
 */
public interface LoginNotification {

    /**
     * Проверяет, нужно ли показывать этот блок данному игроку.
     * Может читать permission, конфиг, кэш (НЕ должен запускать тяжёлые операции —
     * весь тяжёлый расчёт обязан быть завершён заранее, синхронный вызов должен быть дешёвым).
     */
    boolean shouldNotify(Player player);

    /**
     * Возвращает содержимое блока БЕЗ внешнего оформления
     * (без общего заголовка "[1b1v]", без пустых строк-отступов сверху/снизу).
     * Может содержать кликабельные элементы (кнопки).
     */
    Component render(Player player);

    /**
     * Вызывается диспетчером ПОСЛЕ того, как блок реально попал в отправленное игроку сообщение.
     * Здесь и только здесь допустимы побочные эффекты (cooldown, пометка "показано").
     * Раньше это было частью send() — теперь явно отделено от рендера.
     */
    default void onShown(Player player) {
        // по умолчанию — no-op, не все источники имеют cooldown (например, AssetSyncNotification)
    }

    /**
     * Порядок отображения блока в дайджесте (меньше — выше). Дубликаты допустимы,
     * в этом случае порядок между ними не определён.
     */
    default int getPriority() {
        return 100; // нейтральное значение по умолчанию
    }
}